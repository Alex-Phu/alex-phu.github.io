"""Usage: python tools/build_pages.py
Writes projects/<id>.html for every project in data/projects.json that has a "page" and "details".
The pages are plain HTML (no JavaScript needed to read them), so they load fast and work when shared as a link.
Run it again after editing data/projects.json or data/site.json."""
import html, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
data = json.load(open(os.path.join(ROOT, 'data', 'projects.json'), encoding='utf-8'))
site = json.load(open(os.path.join(ROOT, 'data', 'site.json'), encoding='utf-8'))
e = lambda s: html.escape(str(s), quote=True)
up = lambda path: '../' + path  # pages live one folder down from the site root
problems = []


def link(l):
    return f'<a class="btn" href="{e(l["url"])}" target="_blank" rel="noopener">{e(l["label"])} ↗</a>'


def figure(m, hero=False):
    if not os.path.exists(os.path.join(ROOT, m['src'])):
        problems.append('missing file: ' + m['src'])
    size = f'width="{m["width"]}" height="{m["height"]}"'
    if m['type'] == 'video':
        poster = f' poster="{e(up(m["poster"]))}"' if m.get('poster') else ''
        body = (f'<video src="{e(up(m["src"]))}"{poster} {size} autoplay muted loop playsinline controls preload="metadata" '
                f'aria-label="{e(m["alt"])}"></video>')
    else:
        lazy = '' if hero else ' loading="lazy"'
        body = (f'<a href="{e(up(m["src"]))}" target="_blank" rel="noopener" aria-label="Open full size">'
                f'<img src="{e(up(m["src"]))}" alt="{e(m["alt"])}" {size}{lazy}></a>')
    cap = f'<figcaption>{e(m["caption"])}</figcaption>' if m.get('caption') else ''
    return f'<figure class="media{" hero" if hero else ""}">{body}{cap}</figure>'


def page(p):
    d = p['details']
    media = p.get('media') or []
    hero = figure(media[0], hero=True) if media else ''
    more = ''.join(figure(m) for m in media[1:])
    steps = ''.join(f'<li><span class="n">{i}</span>{e(s)}</li>' for i, s in enumerate(d['steps'], 1))
    sections = [
        f'<section><h2>What I built</h2><ul class="built">{"".join(f"<li>{e(b)}</li>" for b in d["built"])}</ul></section>',
        f'<section><h2>How it works</h2><ol class="flow">{steps}</ol></section>',
    ]
    if more:
        sections.append(f'<section><h2>Screens</h2>{more}</section>')
    if p.get('tech'):
        sections.append(f'<section><h2>Tools</h2><ul class="chips">{"".join(f"<li>{e(t)}</li>" for t in p["tech"])}</ul></section>')
    if d.get('results'):
        sections.append(f'<section><h2>Status</h2><ul class="built">{"".join(f"<li>{e(r)}</li>" for r in d["results"])}</ul></section>')
    links = ''.join(link(l) for l in p.get('links') or [])
    if links:
        sections.append(f'<section class="links">{links}</section>')
    meta = f'<p class="meta">{e(p["meta"])}</p>' if p.get('meta') else ''
    mail = e(site['email'])
    return f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>{e(p["title"])} · Alex Phu</title>
<meta name="description" content="{e(p.get("summary") or p["short"])}">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=VT323&family=IBM+Plex+Sans:wght@400;600&display=swap" rel="stylesheet">
<link rel="stylesheet" href="../css/project.css">
</head>
<body>
<!-- Generated by tools/build_pages.py from data/projects.json. Edit the JSON, then run the script. -->
<header class="top">
  <a class="name" href="../">Alex Phu</a>
  <a class="back" href="../">← Back to the desk</a>
</header>
<main>
  <p class="tag">{e(p.get("tag", ""))}</p>
  <h1>{e(p["title"])}</h1>
  {meta}
  <p class="lead">{e(p.get("summary") or p["short"])}</p>
  {hero}
  {"".join(sections)}
</main>
<footer>
  <p>Questions about {e(p["title"])}? Email <a href="mailto:{mail}">{mail}</a></p>
  <p><a href="../">Explore the rest of the desk</a></p>
</footer>
<script>
  // Autoplaying demos stay paused for people who ask for reduced motion.
  if (matchMedia('(prefers-reduced-motion: reduce)').matches) document.querySelectorAll('video').forEach((v) => {{ v.removeAttribute('autoplay'); v.pause(); }});
</script>
</body>
</html>
'''


os.makedirs(os.path.join(ROOT, 'projects'), exist_ok=True)
for p in data['projects']:
    if not (p.get('page') and p.get('details')):
        continue
    out = os.path.join(ROOT, p['page'])
    open(out, 'w', encoding='utf-8').write(page(p))
    print('wrote', p['page'])
if problems:
    sys.exit('\n'.join(problems))
